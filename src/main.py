# данные о студентах
'''
Алгоритм решения:
1. Читаем файл.
2. Используем регулярное выражение для извлечения данных: имя студента, группу и средний балл.
3. Сохраняем данные в словарь и добавляем его в список.
4. Выводим список с форматированным выводом.
'''

import os
import re

script_path = os.path.dirname(os.path.abspath(__file__))
file_path = os.path.join(script_path, 'data.txt')

# Открытие файла для чтения
with open(file_path, 'r', encoding='utf-8') as f:
    students = []
    
    # Регулярное выражение для извлечения данных
    pattern = r'Имя:\s([А-Яа-я]+),\sГруппа:\s([A-Z0-9]+),\sСредний\sбалл:\s([0-9]+\.[0-9]{2})'
    
    # Чтение файла построчно
    for line in f:
        # Ищем совпадения с паттерном
        match = re.search(pattern, line)
        if match:
            # Извлекаем данные
            name = match.group(1)
            group = match.group(2)
            average_grade = float(match.group(3))
            
            # Добавляем данные в список как словарь
            students.append({
                'Имя': name,
                'Группа': group,
                'Средний балл': average_grade
            })
    
    # Вывод информации о студентах
    for student in students:
        print(f'Имя: {student["Имя"]},')
        print(f'Группа: {student["Группа"]},')
        print(f'Средний балл: {student["Средний балл"]}')
        print()  # Печатаем пустую строку между студентами
