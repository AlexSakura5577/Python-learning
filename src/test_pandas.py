# Задача 2: Заполнение пропущенных значений
# Необходимо заполнить пропущенные значения в данных:

# ✅ Для столбца "марка машины" замените пропуски на строку "Не указано".
# ✅ Для столбца "год выпуска" замените пропуски на значение 0.
# ✅ Для столбца "цена" замените пропуски на медиану цен.

import pandas as pd
import numpy as np

# Прочитаем данные
df = pd.read_csv("src/cars_broken.csv")

# Заменяем пустые строки на NaN для столбца "цена"
df["цена"] = df["цена"].replace("", np.nan)

# Убираем пробелы и преобразуем в числовой формат
df["цена"] = df["цена"].str.replace(" ", "").apply(pd.to_numeric, errors='coerce')

# Заполняем пропущенные значения
df["марка машины"] = df["марка машины"].fillna("Не указано")
df["год выпуска"] = df["год выпуска"].fillna(0)
df["цена"] = df["цена"].fillna("Бесценна")
# Метод .fillna() используется для заполнения пропущенных значений в DataFrame или Series.

# Округляем числовые значения года до целых чисел
df["год выпуска"] = df["год выпуска"].round().astype(int)

# Округляем числовые значения цены до целых чисел, если цена - не "Бесценна"
df["цена"] = df["цена"].apply(lambda x: round(x) if isinstance(x, (int, float)) else x)
# Метод .apply() позволяет применить функцию ко всем элементам в столбце или строке DataFrame.
# isinstance(x, (int, float)) — Это проверка типа данных

# Сохраняем обновлённые данные
df.to_csv("src/cars_corrected.csv", index=False, encoding="utf-8")

# Выводим обновлённые данные
print("Пропущенные значения были заполнены. Вот обновлённые данные:")
print(df)

