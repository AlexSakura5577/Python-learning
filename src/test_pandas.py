import pandas as pd

df = pd.DataFrame({
    'имя': ['Ольга', 'Андрей', 'Светлана'],
    'город': ['Москва', 'Казань', 'Екатеринбург'],
    'сумма заказа': [7000, 4000, 10000]
})

# 🔥 ТВОЙ КОД ЗДЕСЬ
# Добавить нового клиента "Дмитрий" из "Тюмени" с заказом на 2500 руб.
# df.loc[3] = ['Дмитрий', 'Тюмень', 2500]
df.loc[len(df)] = ['Дмитрий', 'Тюмень', 2500]

# Добавить новый столбец "доставка" с фиксированной ценой 500 руб.
df['доставка'] = [500, 500, 500, 500]

# Удалить все заказы ниже 5000 руб. (включая доставку).
# df = df[df['сумма заказа'] > 5000] # оставляем только строки больше 5000
df = df[df['сумма заказа'] + df['доставка'] > 5000]

print(df)
